#!/usr/bin/env python3
"""Verify the lossless PR packaging projection or restore its historical evidence tree.

Verification is read-only; --check-git also checks the fixed pre-cleanup Git tree. Restoration
requires a fresh destination and writes only previously verified regular files.
This does not unpack measurement/validation archives or rerun their CPU/GPU work.
"""
import argparse
import gzip
import hashlib
import io
import json
import os
from pathlib import Path, PurePosixPath
import subprocess
import tarfile

BASE = 'studies/model_generation/engine-prefix-evidence'
PRE_CLEANUP = '17ad71ea7f4e4de2553a60a71a4fc2940bc714a5'
KIND = 'engine-prefix-evidence-packaging-v1'
MANIFEST_SHA256 = '12414ad952e416c8b6d48eac54776582bf543c9ec3b510843d824ff894237044'
CAMPAIGNS = {
    'prefix': ('', ('README.md', 'engine-prefix-results.json', 'independent-audit/audit.json')),
    'active': ('active-prefill', ('README.md', 'engine-prefix-active-results.json', 'independent-raw-audit.json')),
    'adaptive': ('adaptive-prefill', ('README.md', 'engine-prefix-adaptive-results.json', 'independent-raw-audit.json', 'independent-decision-audit.json')),
    'frequency': ('frequency-prefill', ('README.md', 'engine-prefix-frequency-results.json', 'independent-raw-audit.json', 'independent-decision-audit.json')),
}
INVENTORIES = ('artifact-inventory.json', 'active-prefill/artifact-inventory.json',
               'adaptive-prefill/final-inventory.json', 'frequency-prefill/final-inventory.json')
SOURCE_SUFFIXES = {'.mojo', '.py', '.json', '.gz', '.lock'}
HISTORICAL_EXCEPTION = {'inventory': 'active-prefill/artifact-inventory.json', 'member': 'retention/__pycache__/prefix_retention.cpython-312.pyc', 'bytes': 33984, 'sha256': 'b9d9e1d22ca8e2c2ac770645dc3e11ed85fa7f9775a5d3b6dfb1f552ac3863af', 'reason': 'Ignored generated bytecode was listed by the historical inventory but absent from the pre-cleanup Git tree; not restored or silently substituted.'}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def decode(raw):
    def unique(items):
        result = {}
        for key, value in items:
            require(key not in result, 'duplicate JSON key: '+key)
            result[key] = value
        return result
    def invalid(value):
        raise ValueError('nonfinite JSON constant: '+value)
    return json.loads(raw, object_pairs_hook=unique, parse_constant=invalid)


def safe(name):
    require(type(name) is str and name and '\\' not in name and '\x00' not in name,
            'invalid retained path')
    value = PurePosixPath(name)
    require(not value.is_absolute() and '..' not in value.parts and str(value) == name and name != '.',
            'unsafe retained path: '+name)
    return value


def binding(raw):
    return dict(bytes=len(raw), sha256=sha(raw))


def checked(raw, expected, label):
    require(type(expected.get('bytes')) is int and len(raw) == expected['bytes']
            and sha(raw) == expected.get('sha256'), 'byte identity differs: '+label)
    return raw


def git(root, *args, data=None):
    return subprocess.run(['git', *args], cwd=root, input=data, check=True,
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE).stdout


def git_tree(root):
    require(git(root, 'rev-parse', PRE_CLEANUP+'^{commit}').decode().strip() == PRE_CLEANUP,
            'pre-cleanup Git commit is unavailable')
    result = {}
    for row in git(root, 'ls-tree', '-r', '-z', PRE_CLEANUP).split(b'\0'):
        if row:
            meta, name = row.split(b'\t', 1)
            mode, kind, blob = meta.decode().split()
            require(kind == 'blob', 'unexpected Git tree entry')
            result[name.decode()] = dict(mode=mode, git_blob=blob)
    return result


def git_bodies(root, tree):
    ids = sorted({entry['git_blob'] for entry in tree.values()})
    stream = io.BytesIO(git(root, 'cat-file', '--batch', data=('\n'.join(ids)+'\n').encode()))
    result = {}
    for blob in ids:
        header = stream.readline().decode().split()
        require(len(header) == 3 and header[:2] == [blob, 'blob'], 'invalid Git blob response')
        size = int(header[2]); raw = stream.read(size)
        require(len(raw) == size and stream.read(1) == b'\n', 'truncated Git blob')
        result[blob] = raw
    require(stream.read() == b'', 'unexpected Git blob response suffix')
    return result


def git_source(name, tree, bodies, depth=0):
    require(depth < 12 and name in tree, 'missing/cyclic Git source: '+name)
    entry = tree[name]; raw = bodies[entry['git_blob']]
    if entry['mode'] == '120000':
        target = raw.decode(); require(not PurePosixPath(target).is_absolute(), 'absolute source symlink')
        resolved = os.path.normpath(str(PurePosixPath(name).parent / target))
        safe(resolved)
        return git_source(resolved, tree, bodies, depth+1)
    require(entry['mode'].startswith('100'), 'nonregular Git source: '+name)
    return raw


def source_paths(tree):
    return sorted(name for name in tree if (name.startswith(('src/', 'tests/'))
                  and PurePosixPath(name).suffix in SOURCE_SUFFIXES)
                  or name in ('pyproject.toml', 'uv.lock'))


def expected_members():
    return {name: [str(PurePosixPath(folder) / member) if folder else member for member in members]
            for name, (folder, members) in CAMPAIGNS.items()}


def package_name(campaign):
    folder = CAMPAIGNS[campaign][0]
    return str(PurePosixPath(folder) / 'supplementary.tar.gz') if folder else 'supplementary.tar.gz'


def package_contents(path, description, allowed):
    require(path.is_file() and not path.is_symlink(), 'package must be a regular file: '+str(path))
    packed = checked(path.read_bytes(), description, str(path))
    require(packed[:3] == b'\x1f\x8b\x08' and packed[4:8] == b'\0\0\0\0',
            'package gzip timestamp is not deterministic')
    size = description['tar_bytes']; require(type(size) is int and size >= 0, 'invalid tar bound')
    with gzip.GzipFile(fileobj=io.BytesIO(packed)) as source:
        raw = source.read(size+1)
        require(len(raw) == size and source.read(1) == b'', 'uncompressed package size differs')
    files = {}
    with tarfile.open(fileobj=io.BytesIO(raw), mode='r:') as archive:
        for entry in archive:
            safe(entry.name)
            require(entry.name in allowed and entry.name not in files, 'unexpected/duplicate tar member: '+entry.name)
            require(entry.isfile() and not entry.linkname and not entry.pax_headers
                    and entry.uid == entry.gid == entry.mtime == 0 and entry.mode == 0o644
                    and entry.uname == entry.gname == '', 'noncanonical/nonregular tar member: '+entry.name)
            expected = allowed[entry.name]
            require(entry.size == expected['bytes'], 'tar member size differs: '+entry.name)
            stream = archive.extractfile(entry)
            require(stream is not None, 'missing tar member body')
            files[entry.name] = checked(stream.read(entry.size+1), expected, entry.name)
    require(set(files) == set(allowed), 'missing package member')
    return files


def inventory_check(files, exceptions):
    require(exceptions == [HISTORICAL_EXCEPTION], 'historical inventory exception differs')
    count = 0; missing = []
    for name in INVENTORIES:
        receipt = decode(files[name]); prefix = PurePosixPath(name).parent
        for relative, expected in receipt['files'].items():
            safe(relative)
            target = str(prefix / relative)
            if target not in files:
                require(name == HISTORICAL_EXCEPTION['inventory'] and relative == HISTORICAL_EXCEPTION['member']
                        and expected == {key: HISTORICAL_EXCEPTION[key] for key in ('bytes', 'sha256')},
                        'inventory target missing: '+target)
                missing.append(target)
            else:
                checked(files[target], expected, name+':'+target)
                count += 1
    require(missing == ['active-prefill/'+HISTORICAL_EXCEPTION['member']], 'historical missing-member census differs')
    return count


def verify(root, manifest_path, live_sources=False, check_git=False):
    manifest_raw = manifest_path.read_bytes()
    require(sha(manifest_raw) == MANIFEST_SHA256, 'independent packaging manifest SHA differs')
    manifest = decode(manifest_raw)
    require(manifest['kind'] == KIND and manifest['schema_version'] == 1
            and manifest['pre_cleanup_commit'] == PRE_CLEANUP, 'packaging identity differs')
    originals = manifest['original_files']
    require(len(originals) == 96 and all(str(safe(name)).startswith(BASE+'/') for name in originals),
            'original evidence census/path differs')
    members = expected_members(); supplementary = {}
    require(set(manifest['packages']) == set(CAMPAIGNS), 'package census differs')
    for campaign, names in members.items():
        desc = manifest['packages'][campaign]
        require(desc['path'] == package_name(campaign) and set(desc['members']) == set(names), 'package membership differs')
        allowed = {}
        for name in names:
            expected = desc['members'][name]; original = BASE+'/'+name
            require(expected == originals[original], 'member/original binding differs: '+name)
            allowed[name] = expected
        supplementary.update(package_contents(root/BASE/desc['path'], desc, allowed))
    require(len(supplementary) == 14, 'supplementary member census differs')
    files = {}; present_reports = 0
    for original, entry in originals.items():
        name = str(PurePosixPath(original).relative_to(BASE)); current = root/original
        body = supplementary.get(name)
        if body is None:
            require(current.is_file() and not current.is_symlink(), 'unchanged evidence missing: '+original)
            body = checked(current.read_bytes(), entry, original)
        elif PurePosixPath(name).name != 'README.md' and current.exists():
            require(current.is_file() and not current.is_symlink(), 'expanded report is nonregular: '+original)
            checked(current.read_bytes(), entry, original); present_reports += 1
        checked(body, entry, original)
        object_id = hashlib.sha1(b'blob '+str(len(body)).encode()+b'\0'+body).hexdigest()
        require(object_id == entry['git_blob'], 'original Git blob identity differs: '+original)
        files[name] = body
    archives = {name: binding(files[str(PurePosixPath(name).relative_to(BASE))])
                for name in originals if name.endswith('.json.gz')}
    require(len(archives) == 8 and manifest['unchanged_archives'] == archives, 'original archive bindings differ')
    baseline = manifest['packaging_source_baseline']; source_map = baseline['sources']
    require(baseline['commit'] == PRE_CLEANUP and len(source_map) == 271, 'source baseline identity/census differs')
    for name, expected in source_map.items():
        safe(name)
        require((name.startswith(('src/', 'tests/')) and PurePosixPath(name).suffix in SOURCE_SUFFIXES)
                or name in ('pyproject.toml', 'uv.lock'), 'invalid source baseline path')
        require(type(expected) is str and len(expected) == 64 and all(c in '0123456789abcdef' for c in expected),
                'invalid source baseline digest')
    if check_git:
        tree = git_tree(root)
        relevant = {name: entry for name, entry in tree.items()
                    if name.startswith(BASE+'/') or name in source_paths(tree)}
        bodies = git_bodies(root, relevant)
        require(set(originals) == {name for name in tree if name.startswith(BASE+'/')}, 'original Git evidence census differs')
        for original, entry in originals.items():
            require(tree[original]['mode'].startswith('100') and entry['git_blob'] == tree[original]['git_blob']
                    and files[str(PurePosixPath(original).relative_to(BASE))] == bodies[entry['git_blob']],
                    'original evidence differs from pre-cleanup Git: '+original)
        require(source_map == {name: sha(git_source(name, tree, bodies)) for name in source_paths(tree)},
                'recorded source baseline differs from pre-cleanup Git')
    if live_sources:
        actual_names = sorted(str(path.relative_to(root)) for parent in ('src', 'tests')
            for path in (root/parent).rglob('*') if path.is_file() and path.suffix in SOURCE_SUFFIXES)
        actual_names += ['pyproject.toml', 'uv.lock']
        require(set(actual_names) == set(source_map), 'live source census changed since packaging baseline')
        for name, expected in source_map.items():
            require(sha((root/name).read_bytes()) == expected, 'live source differs from packaging-only baseline: '+name)
    checked_inventory = inventory_check(files, manifest['historical_inventory_exceptions'])
    report = dict(kind='engine-prefix-evidence-packaging-verification-v1', status='passed',
        pre_cleanup_commit=PRE_CLEANUP, packages=4, supplementary_members=14,
        original_files=len(files), unchanged_archives=8, original_inventory_bindings=checked_inventory,
        historical_unrestorable_bindings=manifest['historical_inventory_exceptions'],
        inventory_scope='Three inventories fully restorable; active artifact inventory has one pre-existing ignored-bytecode exception.',
        baseline_source_files=len(source_map), git_baseline_check='matched' if check_git else 'not requested; portable manifest/blob verification only',
        live_source_check='matched packaging-only baseline' if live_sources else 'not requested; later integration may change live sources',
        expanded_reports_present=present_reports, manifest_sha256=sha(manifest_path.read_bytes()),
        large_archive_decode=False, native_execution=False)
    return files, report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[4],
                        help='Repository containing the unchanged evidence files; Git is required only with --check-git')
    commands = parser.add_subparsers(dest='command', required=True)
    check = commands.add_parser('verify', help='Pure read-only verification; no extraction')
    check.add_argument('--check-git', action='store_true', help='Also compare all original bytes and source hashes to the fixed pre-cleanup Git tree')
    check.add_argument('--check-live-sources', action='store_true', help='Also require the current packaging-only source baseline')
    restore = commands.add_parser('restore', help='Reconstruct the original evidence tree at a fresh destination')
    restore.add_argument('--check-git', action='store_true', help='Also compare the fixed pre-cleanup Git tree before restoration')
    restore.add_argument('--directory', type=Path, required=True)
    args = parser.parse_args(); root = args.root.resolve()
    files, result = verify(root, root/BASE/'packaging-manifest.json', getattr(args, 'check_live_sources', False), args.check_git)
    if args.command == 'restore':
        destination = args.directory.absolute()
        require(not destination.exists() and not destination.is_symlink(), 'restore destination must be fresh')
        destination.mkdir(parents=True)
        for name, body in sorted(files.items()):
            target = destination/Path(safe(name)); target.parent.mkdir(parents=True, exist_ok=True)
            with target.open('xb') as stream:
                stream.write(body)
        result['restored_directory'] = str(destination)
        result['restored_files'] = len(files)
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    main()
